import {test,expect} from '@playwright/test'
test('登记候选和已选显示准确学习小组，空白和旧来源组不冒充学习小组',async({page})=>{
 await page.goto('/tests/fixtures/learning-group.html')
 const input=page.getByRole('combobox',{name:'搜索姓名、公司或学习小组'})
 await input.fill('学习组甲')
 await expect(page.getByRole('option')).toHaveCount(1)
 await expect(page.locator('.candidate-person')).toContainText('示例甲')
 await expect(page.locator('.candidate-person .learning-group')).toHaveText('示例学习组甲')
 await expect(page.locator('.candidate-person')).not.toContainText('学习小组：')
 await input.fill('示例甲')
 await expect(page.locator('.candidate-person')).toContainText('示例学习组甲')
 await input.press('Enter')
 await expect(page.locator('.selected-person-info .learning-group')).toHaveText('示例学习组甲')
 await expect(page.locator('.selected-person-info')).not.toContainText('学习小组：')
 await expect(input).toHaveValue('');await expect(input).toBeFocused()
 await input.fill('示例乙');await expect(page.locator('.candidate-person .learning-group')).toHaveCount(0)
 await page.getByRole('button',{name:'添加 示例乙，虚构企业乙',exact:true}).click()
 await expect(page.locator('.selected-person-info').filter({hasText:'示例乙'}).locator('.learning-group')).toHaveCount(0)
 await input.fill('示例丙');await expect(page.locator('.candidate-person')).not.toContainText('旧来源组')
 await page.getByRole('button',{name:'确认登记'}).click();await expect(page.getByRole('heading',{name:'登记成功：001 号'})).toBeVisible()
})
