import { test, expect, type Page } from '@playwright/test'
import ExcelJS from 'exceljs'
import roster from '../../src/data/demo-roster.json' with { type: 'json' }
const [a,b,c,d,e,f] = roster
async function add(page: Page, p: typeof a, keyboard = false) {
  const input=page.getByRole('combobox',{name:'搜索姓名、公司或学习小组'})
  await input.fill(p.name)
  if (keyboard) await input.press('Enter')
  else await page.getByRole('button',{name:`添加 ${p.name}，${p.company || '未填写公司'}`,exact:true}).click()
  await expect(input).toHaveValue('')
  await expect(input).toBeFocused()
}
async function next(page: Page) {
  await page.getByRole('button',{name:'下一位接人者'}).click()
  await expect(page.getByRole('combobox')).toBeFocused()
}
