test('Enter安全规则：空词及空白不添加、多候选需方向选择、变更词取消旧选择',async({page})=>{
  await page.goto('/')
  const input=page.getByRole('combobox')
  const chosen=page.locator('.selected-person')
  await input.press('Enter')
  await input.press('ArrowDown')
  await input.press('Enter')
  await expect(chosen).toHaveCount(0)
  await input.fill('   ')
  await input.press('Enter')
  await expect(chosen).toHaveCount(0)
  await input.fill(a.company)
  expect(await page.getByRole('option').count()).toBeGreaterThan(1)
  await page.getByRole('option').nth(0).hover()
  await input.press('Enter')
  await expect(chosen).toHaveCount(0)
  await input.press('ArrowDown')
  await expect(page.getByRole('option').nth(0)).toHaveAttribute('aria-selected','true')
  await input.press('Enter')
  await expect(chosen).toHaveCount(1)
  await expect(chosen).toContainText(a.name)
  await expect(input).toHaveValue('')
  await expect(input).toBeFocused()
  await input.press('Enter')
  await expect(chosen).toHaveCount(1)
  await input.fill(a.company)
  await input.press('ArrowDown')
  await input.fill('志工')
  await input.press('Enter')
  await expect(chosen).toHaveCount(1)
  await input.press('Escape')
  await input.press('Enter')
  await expect(chosen).toHaveCount(1)
  await input.press('ArrowUp')
  await expect(page.getByRole('option').last()).toHaveAttribute('aria-selected','true')
  await input.press('Enter')
  await expect(chosen).toHaveCount(2)
  await input.fill('不存在的人员关键词')
  await input.press('Enter')
  await expect(chosen).toHaveCount(2)
  await add(page,d,true)
  await expect(chosen).toHaveCount(3)
  await input.press('Enter')
  await expect(chosen).toHaveCount(3)
})

test('应急台账实际下载：不受搜索筛选影响，全部人员及撤销后的最大空号仍保留',async({page})=>{
  await page.goto('/manage')
  await expect(page.getByRole('button',{name:'导出应急台账'})).toBeEnabled()
  await expect(page.getByRole('button',{name:'导出会场 Excel'})).toBeDisabled()
  await page.getByRole('link',{name:'接人登记',exact:true}).click()
  await add(page,a)
  await page.getByRole('button',{name:'确认登记'}).click()
  await next(page)
  await add(page,b)
  await page.getByRole('button',{name:'确认登记'}).click()
  await page.getByRole('link',{name:'名单管理',exact:true}).click()
  await page.getByRole('row').filter({hasText:b.name}).getByRole('button').click()
  await page.getByLabel('纠正后的号码').selectOption('unassigned')
  await page.getByRole('button',{name:'保存纠正'}).click()
  await page.getByRole('textbox',{name:'查询名单'}).fill(a.name)
  await page.getByLabel('分配状态筛选').selectOption('1')
  const downloading=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出应急台账'}).click()
  const download=await downloading
  expect(download.suggestedFilename()).toMatch(/^应急台账_本地模拟_\d{14}\.xlsx$/)
  const workbook=new ExcelJS.Workbook()
  await workbook.xlsx.readFile((await download.path())!)
  const all=workbook.getWorksheet('全部人员')!
  expect(all.rowCount).toBe(153)
  roster.forEach((p,index)=>expect([2,3,4].map(col=>all.getRow(index+2).getCell(col).value)).toEqual([p.name,p.company,p.id===a.id?'001':'未分配']))
  const numbers=workbook.getWorksheet('已发号码')!
  expect(numbers.getCell('A2').value).toBe('001')
  expect(numbers.getCell('A3').value).toBe('002')
  expect(numbers.getCell('B3').value).toBe(0)
  expect(workbook.getWorksheet('台账说明')!.getCell('B3').value).toBe('002')
  expect(workbook.getWorksheet('台账说明')!.getCell('B4').value).toBe('003')
})
