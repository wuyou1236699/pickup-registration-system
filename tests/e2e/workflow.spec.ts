test('键盘连续登记、方向选择、去重移除、Escape 与中文组合输入保护',async({page})=>{
  await page.goto('/')
  const input=page.getByRole('combobox')
  await expect(input).toBeFocused()
  await input.fill(a.company)
  const options=page.getByRole('option')
  const firstText=await options.nth(1).locator('.candidate-person strong').textContent()
  await input.press('ArrowDown')
  await expect(options.nth(0)).toHaveAttribute('aria-selected','true')
  await input.press('ArrowDown')
  await expect(options.nth(1)).toHaveAttribute('aria-selected','true')
  await input.press('ArrowUp')
  await expect(options.nth(0)).toHaveAttribute('aria-selected','true')
  await input.press('ArrowDown')
  await input.press('Enter')
  expect(await page.locator('.selected-person').textContent()).toContain(firstText!.trim())
  await page.locator('.selected-person button').click()
  await expect(page.locator('.selected-person')).toHaveCount(0)
  await input.fill(a.name)
  await input.dispatchEvent('compositionstart')
  await input.press('Enter')
  await input.press('Control+Enter')
  await expect(page.locator('.selected-person')).toHaveCount(0)
  await input.dispatchEvent('compositionend')
  await input.press('Escape')
  await expect(input).toHaveAttribute('aria-expanded','false')
  await input.press('Enter')
  await expect(page.locator('.selected-person')).toHaveCount(0)
  await input.fill('')
  await input.fill(a.name)
  await input.press('Enter')
  await input.fill(a.name)
  await expect(page.getByRole('button',{name:`添加 ${a.name}，${a.company || '未填写公司'}`,exact:true})).toHaveCount(0)
  await add(page,b,true)
  await input.press('Control+Enter')
  await expect(page.getByRole('heading',{name:'登记成功：001 号'})).toBeVisible()
  await next(page)
  await add(page,c,true)
  await input.press('Control+Enter')
  await expect(page.getByRole('heading',{name:'登记成功：002 号'})).toBeVisible()
})
